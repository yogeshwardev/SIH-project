const LOCALES = STUDIO_LANGUAGES.map((option) => option.locale);

/** Map a language name, native name or speech code to a supported locale. */
export const localeForLanguage = (language) => {
  const value = String(language || '').trim().toLowerCase();
  if (!value) return 'en';
  if (ALIASES[value]) return ALIASES[value];
  const code = value.split('-')[0].split('_')[0];
  if (LOCALES.includes(code)) return code;
  const match = Object.keys(ALIASES).find((alias) => value.includes(alias));
  return match ? ALIASES[match] : 'en';
};

/** Speech / voice code (BCP-47) for a language name or locale. */
export const speechCodeForLanguage = (language) => {
  const locale = localeForLanguage(language);
  return (STUDIO_LANGUAGES.find((option) => option.locale === locale) || STUDIO_LANGUAGES[8]).code;
};

